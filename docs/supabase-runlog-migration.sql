-- 得物蓝V · 任务级运行日志增量迁移
-- 在现有 Supabase 项目的 SQL Editor 执行一次即可，重复执行安全。
--
-- 新表与现有 publish_log 一样由 anon key 追加和只读查询，因此在线看板保持公开可读。
-- 不上传逐步过程日志、素材内容或绝对路径；App 只发任务 start/end 和过滤后的错误摘要。

create table if not exists public.run_log (
  id            bigint generated by default as identity primary key,
  org           text         not null default 'bluev',
  event_id      text         not null,
  ts            bigint       not null,
  machine_id    text         not null,
  machine_name  text,
  task_id       text,
  event_kind    text         not null check (event_kind in ('start', 'end')),
  task_type     text,
  task_label    text,
  batch_no      text,
  brand_id      text,
  brand_name    text,
  user_id       text,
  username      text,
  display_name  text,
  ok            boolean,
  cancelled     boolean      not null default false,
  elapsed_sec   numeric,
  error_summary text         not null default '',
  created_at    timestamptz  not null default now()
);

create unique index if not exists run_log_dedup
  on public.run_log (machine_id, event_id);
create index if not exists run_log_ts_idx
  on public.run_log (ts desc);

alter table public.run_log enable row level security;

drop policy if exists "run_log_insert_anon" on public.run_log;
create policy "run_log_insert_anon"
  on public.run_log for insert to anon
  with check (org = 'bluev');

drop policy if exists "run_log_select_anon" on public.run_log;
create policy "run_log_select_anon"
  on public.run_log for select to anon
  using (true);

-- 自检：应返回 0 或最近事件；策略应只有 INSERT 与 SELECT。
select count(*) as row_count from public.run_log;
select policyname, cmd from pg_policies
  where schemaname = 'public' and tablename = 'run_log'
  order by cmd;
select indexname from pg_indexes
  where schemaname = 'public' and tablename = 'run_log';
