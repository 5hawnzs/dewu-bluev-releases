-- 在 Supabase 控制台 → SQL Editor 里整段贴进去跑一次即可（幂等，重复跑不会重建数据）。
--
-- ★ 这条线只做一件小事：各台机器把「本机新增的发布结果」推上来，网页看板只读聚合。
--   它**不参与发布**，发布仍然只能由本机 adb 驱动模拟器完成（浏览器碰不到 adb）。
--
-- ★★ 三条红线（改这段 SQL 前先读）：
--   1) 只给 anon 角色 **insert + select**，**绝不给 update / delete**。
--      理由：一旦网页能改，看板上的数字就不再可信（「改失败变成功」只需一行 JS）。
--      执行结果只能由执行端自己上行，谁都不许回头改。
--   2) 客户端（App 和看板）只许用 **anon public key**。
--      **service_role key 不许出现在任何客户端、任何前端、任何仓库文件里** ——
--      它绕过下面所有策略，泄了等于整张表裸奔。
--   3) 表里**不含素材内容、不含绝对路径**（App 侧只取目录最后一段作为款名）。
--      想加字段前先问一句：这一列会不会把本机的东西带出去？
-- =============================================================================

-- ---------- 1. 结果表 ----------
create table if not exists public.publish_log (
  id            bigint generated by default as identity primary key,
  ts            bigint       not null,          -- 发布时间（毫秒）
  machine_id    text         not null,          -- 本机标识（首次同步时生成，写在本机配置里）
  machine_name  text,                           -- 本机名称（区分是谁在发）
  batch_no      text,                           -- 批次
  seq           int,                            -- 篇号 / 序号
  item_id       text,                           -- 货号
  dir_name      text,                           -- 素材目录名（只取最后一段）
  kind          text,                           -- 图文 / 视频
  result        text,                           -- 发布成功 / 失败
  reason        text,                           -- 失败原因（已截断 200 字）
  elapsed       numeric,                        -- 单条耗时（秒）
  retries       int,                            -- 重试次数
  mode          text,                           -- adb（真机通道）/ mock
  brand_id      text,
  brand_name    text,                           -- 品牌名存快照：日后改名不会串账
  user_id       text,
  username      text,
  display_name  text,                           -- 执行人
  created_at    timestamptz  not null default now()
);

-- ★ 幂等的唯一键：网络重试 / 重复同步不会产生重复行
--   （客户端每次插入都带 Prefer: resolution=ignore-duplicates，撞上这一行就跳过）
create unique index if not exists publish_log_dedup
  on public.publish_log (machine_id, ts, seq);

-- 看板按时间倒序取最近数据
create index if not exists publish_log_ts_idx
  on public.publish_log (ts desc);

-- ---------- 2. 行级安全（RLS）----------
alter table public.publish_log enable row level security;

-- 执行端上行：只给 insert。
-- 想再收紧就把 with check 换成按机器白名单，例如：
--   with check (machine_id in ('m_ab12cd34', 'm_ef56gh78'))
-- 收紧前先想清楚：新同事加进来要改一次 SQL，换来的是「陌生 key 也塞不进数据」。
drop policy if exists "publish_log_insert_anon" on public.publish_log;
create policy "publish_log_insert_anon"
  on public.publish_log for insert to anon
  with check (true);

-- 看板读取：只给 select。
drop policy if exists "publish_log_select_anon" on public.publish_log;
create policy "publish_log_select_anon"
  on public.publish_log for select to anon
  using (true);

