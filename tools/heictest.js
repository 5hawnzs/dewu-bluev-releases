'use strict';
const fs = require('fs'), path = require('path'), os = require('os'), assert = require('assert');
const imaging = require('../src/main/services/imaging');
const sharp = require('sharp');
(async () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'bluev-heic-'));
  const source = path.join(__dirname, 'fixtures/heic/example.heic');
  const before = fs.readFileSync(source);
  const check = (label, value) => { assert.ok(value, label); console.log('PASS  ' + label); };
  check('内置独立 HEVC 解码器可用', imaging.hasHeif());
  const img = await imaging.readImage(source);
  check('真实 HEVC 样图解码为 1280×854 RGBA', img.width === 1280 && img.height === 854 && img.data.length === 1280 * 854 * 4);
  const dst = path.join(temp, 'converted.jpg');
  await imaging.convertToJpg(source, dst);
  const decoded = await sharp(dst).raw().toBuffer({ resolveWithObject: true });
  check('转换后的 JPEG 可实际解码，尺寸正确且不是全黑', decoded.info.width === 1280 && decoded.info.height === 854 && decoded.data.some(v => v > 64));
  const thumb = Buffer.from(await imaging.shrinkBase64(source, 200), 'base64');
  const meta = await sharp(thumb).metadata();
  check('模型缩略图可解码且不超过设定尺寸', meta.width === 200 && meta.height <= 200);
  await imaging.fitWithin(source, path.join(temp, 'small.jpg'), 300);
  const small = await sharp(path.join(temp, 'small.jpg')).metadata();
  check('HEIC 等比缩放真实生效', small.width === 300 && small.height <= 300);
  const alternate = path.join(temp, 'alternate.heif'); fs.copyFileSync(source, alternate);
  check('HEIF 扩展名同样可解码', (await imaging.readImage(alternate)).width === 1280);
  check('转换没有修改原图', before.equals(fs.readFileSync(source)));
  const bad = path.join(temp, 'corrupt.heic'); fs.writeFileSync(bad, '损坏文件');
  await assert.rejects(() => imaging.readImage(bad), /解码失败/);
  console.log('PASS  损坏 HEIC 明确失败，不伪造转换成功');
})().catch(e => { console.error(e); process.exitCode = 1; });
